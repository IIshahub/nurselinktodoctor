export function getRequestDetail(request: LabRequest): LabRequestDetail {
  if (request.detail) {
    return request.detail;
  }

  const profile = patientProfiles[request.id] ?? {};

  return {
    ...defaultDetail,
    ...profile,
    scheduledDate: request.date,
    scheduledTime: request.time,
    requestDate: request.date,
    requestTime: request.time,
    address: request.address,
    mapQuery: request.address,
    outlinedDiseases: profile.outlinedDiseases ?? defaultDetail.outlinedDiseases,
    diseases: profile.diseases ?? defaultDetail.diseases,
  };
}
